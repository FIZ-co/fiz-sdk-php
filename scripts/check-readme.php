<?php

// Cuts every ```php block of README.md into tests/readme/block-<n>.php and
// lints each one with `php -l`; `composer check:readme` then runs PHPStan at
// max level on them (phpstan.readme.neon), so the README is analysed exactly
// as written.
//
// A block of statements becomes the body of a static method, its `use`
// imports kept at the top of the file. A block that continues an earlier one
// (uses `$fiz`, `$id`, …) gets those names as typed parameters; nothing else
// is added or changed. A block that declares a class is written as it is.

declare(strict_types=1);

/** Names README fragments take from the blocks before them: name → [native type, PHPDoc type]. */
const AMBIENT = [
    'fiz' => ['\Fiz\Fiz', null],
    'id' => ['string', null],
    'draft' => ['array', 'CreateInvoiceParams'],
    'order' => ['array', 'array{id: string}'],
    'accessToken' => ['string', null],
];

$root = dirname(__DIR__);
$out = "$root/tests/readme";
$readme = (string) file_get_contents("$root/README.md");

foreach (glob("$out/*") ?: [] as $file) {
    unlink($file);
}
if (!is_dir($out)) {
    mkdir($out, 0777, true);
}

preg_match_all('/```php\n(.*?)```/s', $readme, $blocks, PREG_SET_ORDER | PREG_OFFSET_CAPTURE);
$failed = false;
foreach ($blocks as $index => $block) {
    [$code, $offset] = $block[1];
    $line = substr_count(substr($readme, 0, $offset), "\n") + 1;
    $code = preg_replace('/^<\?php\s*/', '', $code) ?? $code;
    $header = "<?php\n\n// README.md line $line. Generated by scripts/check-readme.php; do not edit.\n";

    if (preg_match('/^(final |abstract )?(class|interface|function) /m', $code) === 1) {
        $source = "$header\n$code";
    } else {
        preg_match_all('/^use [^;]+;\n/m', $code, $imports);
        // Continuing blocks name the client class without importing it again.
        if (preg_match('/\bnew Fiz\b/', $code) === 1 && !in_array("use Fiz\\Fiz;\n", $imports[0], true)) {
            $imports[0][] = "use Fiz\\Fiz;\n";
        }
        $body = trim(preg_replace(['/^use [^;]+;\n/m', '/\n{3,}/'], ['', "\n\n"], $code) ?? $code);
        $params = [];
        $docs = [];
        foreach (AMBIENT as $name => [$native, $doc]) {
            $used = preg_match('/\$' . $name . '\b/', $body) === 1;
            $assigned = preg_match('/\$' . $name . '\s*=[^=>]/', $body) === 1;
            if ($used && !$assigned) {
                $params[] = "$native \$$name";
                if ($doc !== null) {
                    $docs[] = "     * @param $doc \$$name";
                }
            }
        }
        $docblock = $docs === [] ? '' : "    /**\n" . implode("\n", $docs) . "\n     */\n";
        $source = $header . "\n" . implode('', $imports[0]) . "\n"
            . "/**\n * @phpstan-import-type CreateInvoiceParams from \\Fiz\\Generated\\Types\n */\n"
            . "final class ReadmeBlock$index\n{\n"
            . $docblock
            . '    public static function run(' . implode(', ', $params) . "): void\n    {\n"
            . preg_replace('/^(?=.)/m', '        ', $body) . "\n    }\n}\n";
    }
    $file = "$out/block-$index.php";
    file_put_contents($file, $source);
    exec(escapeshellarg(PHP_BINARY) . ' -l ' . escapeshellarg($file) . ' 2>&1', $output, $status);
    if ($status !== 0) {
        fwrite(STDERR, "README.md line $line: " . implode("\n", $output) . "\n");
        $failed = true;
    }
    $output = [];
}
echo 'README: ' . count($blocks) . " PHP blocks extracted and linted\n";
exit($failed ? 1 : 0);
