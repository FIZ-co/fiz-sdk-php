<?php

// Generates src/Generated/ from openapi/openapi.json. No network access:
// `composer update-spec` refreshes the spec first.
//
//  - Operations.php — operationId → method, path, and whether the route takes
//                     an Idempotency-Key. The client reads this table, so a
//                     method never restates its route by hand.
//  - Types.php      — PHPStan/Psalm array shapes: one per schema of the API
//                     document, plus the body, query and response of every
//                     operation (`InvoicesController_createBody`, …).

declare(strict_types=1);

const HEADER = '// Generated by scripts/generate.php from openapi/openapi.json. Do not edit.';
const METHODS = ['get', 'post', 'put', 'patch', 'delete'];

/**
 * Names the README and the resources use for the most common schemas (the
 * JavaScript SDK exports the same aliases).
 */
const NAMED = [
    'Invoice' => 'InvoiceResponseDto',
    'InvoiceListItem' => 'InvoiceListItemResponseDto',
    'CreateInvoiceParams' => 'CreateInvoiceDto',
    'Customer' => 'CreateCustomerResponseDto',
    'CreateCustomerParams' => 'CreateCustomerDto',
    'Item' => 'CreateItemResponseDto',
    'CreateItemParams' => 'CreateItemDto',
    'Company' => 'CompanyResponseDto',
    'ApiErrorBody' => 'ErrorResponseDto',
];

$root = dirname(__DIR__);
$specPath = "$root/openapi/openapi.json";
$spec = json_decode((string) file_get_contents($specPath), true, 512, JSON_THROW_ON_ERROR);
$schemas = $spec['components']['schemas'] ?? [];

function fail(string $message): never
{
    fwrite(STDERR, "generate: $message\n");
    exit(1);
}

function isIdentifier(string $name): bool
{
    return preg_match('/^[A-Za-z_][A-Za-z0-9_]*$/', $name) === 1;
}

function literal(mixed $value): string
{
    return match (true) {
        $value === null => 'null',
        is_bool($value) => $value ? 'true' : 'false',
        is_int($value), is_float($value) => (string) $value,
        is_string($value) => "'" . addcslashes($value, "'\\") . "'",
        default => fail('unsupported enum value ' . json_encode($value)),
    };
}

function indent(string $text): string
{
    return str_replace("\n", "\n    ", $text);
}

/** @param list<string> $types */
function union(array $types): string
{
    $types = array_values(array_unique($types));
    if (in_array('mixed', $types, true)) {
        return 'mixed';
    }
    // null last, as people write it.
    usort($types, static fn (string $a, string $b): int => ($a === 'null') <=> ($b === 'null'));
    return implode('|', $types);
}

/**
 * The PHP type of a schema. Objects become array shapes (a key the schema
 * does not require is optional: `key?:`), arrays become lists, enums
 * literal unions, `nullable` adds `|null`.
 *
 * @param array<string, mixed> $schema
 */
function typeOf(array $schema): string
{
    if (isset($schema['$ref'])) {
        $name = substr((string) $schema['$ref'], strlen('#/components/schemas/'));
        if (!str_starts_with((string) $schema['$ref'], '#/components/schemas/') || !isIdentifier($name)) {
            fail("unsupported reference {$schema['$ref']}");
        }
        $type = $name;
    } elseif (isset($schema['enum'])) {
        $type = union(array_map('literal', $schema['enum']));
    } elseif (isset($schema['allOf'])) {
        // Used to attach a description or `nullable` to a reference; an
        // intersection of several schemas has no array-shape equivalent.
        $type = count($schema['allOf']) === 1 ? typeOf($schema['allOf'][0]) : 'array<string, mixed>';
    } elseif (isset($schema['oneOf']) || isset($schema['anyOf'])) {
        $type = union(array_map('typeOf', $schema['oneOf'] ?? $schema['anyOf']));
    } else {
        $type = match ($schema['type'] ?? null) {
            'string' => 'string',
            'integer' => 'int',
            'number' => 'float|int',
            'boolean' => 'bool',
            'array' => 'list<' . typeOf($schema['items'] ?? []) . '>',
            'object' => objectType($schema),
            null => isset($schema['properties']) ? objectType($schema) : 'mixed',
            default => fail('unsupported type ' . json_encode($schema['type'])),
        };
    }
    if (($schema['nullable'] ?? false) === true && !in_array($type, ['mixed', 'null'], true) && !str_ends_with($type, '|null')) {
        $type .= '|null';
    }
    return $type;
}

/** @param array<string, mixed> $schema */
function objectType(array $schema): string
{
    $properties = $schema['properties'] ?? [];
    if ($properties === []) {
        $additional = $schema['additionalProperties'] ?? true;
        return is_array($additional) ? 'array<string, ' . typeOf($additional) . '>' : 'array<string, mixed>';
    }
    return shape($properties, $schema['required'] ?? []);
}

/**
 * @param array<string, array<string, mixed>> $properties
 * @param list<string> $required
 */
function shape(array $properties, array $required): string
{
    $lines = [];
    foreach ($properties as $name => $property) {
        $key = isIdentifier((string) $name) ? (string) $name : literal((string) $name);
        $optional = in_array($name, $required, true) ? '' : '?';
        $lines[] = '    ' . $key . $optional . ': ' . indent(typeOf($property)) . ',';
    }
    return "array{\n" . implode("\n", $lines) . "\n}";
}

// --- Operations ---------------------------------------------------------

$operations = [];
foreach ($spec['paths'] as $path => $item) {
    foreach (METHODS as $method) {
        $op = $item[$method] ?? null;
        if ($op === null) {
            continue;
        }
        $id = $op['operationId'] ?? fail(strtoupper($method) . " $path has no operationId");
        if (!isIdentifier($id)) {
            fail("operationId $id is not usable as a type name");
        }
        $operations[$id] = ['method' => strtoupper($method), 'path' => $path, 'op' => $op];
    }
}
ksort($operations, SORT_STRING);

$table = '';
foreach ($operations as $id => $operation) {
    $idempotent = false;
    foreach ($operation['op']['parameters'] ?? [] as $parameter) {
        if ($parameter['in'] === 'header' && strtolower($parameter['name']) === 'idempotency-key') {
            $idempotent = true;
        }
    }
    $table .= sprintf(
        "        %s => [%s => %s, %s => %s, %s => %s],\n",
        literal($id),
        literal('method'),
        literal($operation['method']),
        literal('path'),
        literal($operation['path']),
        literal('idempotent'),
        $idempotent ? 'true' : 'false',
    );
}

$operationsFile = <<<'PHP'
<?php

declare(strict_types=1);

namespace Fiz\Generated;

<HEADER>

/**
 * Every operation of the API document: the client reads its route from here.
 */
final class Operations
{
    /** `info.version` of the API document this SDK was generated from. */
    public const API_VERSION = <VERSION>;

    /** @var array<string, array{method: string, path: string, idempotent: bool}> */
    public const OPERATIONS = [
<TABLE>    ];
}

PHP;
$operationsFile = strtr($operationsFile, [
    '<HEADER>' => HEADER,
    '<VERSION>' => literal((string) $spec['info']['version']),
    '<TABLE>' => $table,
]);

// --- Types --------------------------------------------------------------

/** @var array<string, string> $aliases name → type */
$aliases = [];
foreach ($schemas as $name => $schema) {
    if (!isIdentifier($name)) {
        fail("schema name $name is not usable as a type name");
    }
    $aliases[$name] = typeOf($schema);
}
foreach (NAMED as $name => $target) {
    if (isset($aliases[$name]) || !isset($aliases[$target])) {
        fail("named alias $name → $target clashes with a schema or names a missing one");
    }
    $aliases[$name] = $target;
}

/**
 * @param array<string, mixed>|null $content
 * @return array<string, mixed>|null
 */
function jsonSchema(?array $content): ?array
{
    return $content['application/json']['schema'] ?? null;
}

$responseMap = [];
foreach ($operations as $id => $operation) {
    $op = $operation['op'];
    $body = jsonSchema($op['requestBody']['content'] ?? null);
    if ($body !== null) {
        $aliases["{$id}Body"] = typeOf($body);
    }
    $query = [];
    $required = [];
    foreach ($op['parameters'] ?? [] as $parameter) {
        if ($parameter['in'] === 'query') {
            $query[$parameter['name']] = $parameter['schema'] ?? [];
            if (($parameter['required'] ?? false) === true) {
                $required[] = $parameter['name'];
            }
        }
    }
    if ($query !== []) {
        $aliases["{$id}Query"] = shape($query, $required);
        // What `listAll` takes: the filters, with `pageSize` in place of the
        // paging parameters it drives itself.
        foreach ([['offset', 'limit'], ['page', 'pageSize']] as $paging) {
            if (isset($query[$paging[0]], $query[$paging[1]])) {
                $filters = array_diff_key($query, array_flip($paging));
                $filters['pageSize'] = ['type' => 'integer'];
                $aliases["{$id}ListAllQuery"] = shape($filters, array_values(array_diff($required, $paging)));
            }
        }
    }
    $success = $op['responses']['200'] ?? $op['responses']['201'] ?? null;
    $response = jsonSchema($success['content'] ?? null);
    $aliases["{$id}Response"] = $response === null ? 'mixed' : typeOf($response);
    $responseMap[] = "    $id: {$id}Response,";
}
$aliases['ResponseMap'] = "array{\n" . implode("\n", $responseMap) . "\n}";

$doc = [];
foreach ($aliases as $name => $type) {
    $doc[] = " * @phpstan-type $name " . str_replace("\n", "\n * ", $type);
}
$typesFile = strtr(<<<'PHP'
<?php

declare(strict_types=1);

namespace Fiz\Generated;

<HEADER>

/**
 * The API document's schemas as array shapes, for PHPStan and Psalm. Import
 * one with `@phpstan-import-type Invoice from \Fiz\Generated\Types`.
 *
 * Per operation: `<operationId>Body` (the JSON body), `<operationId>Query`
 * (the query parameters), `<operationId>ListAllQuery` (what `listAll` takes) and
 * `<operationId>Response` (the success body; `mixed` where the API document
 * does not describe it).
 *
<DOC>
 */
final class Types
{
}

PHP, ['<HEADER>' => HEADER, '<DOC>' => implode("\n *\n", $doc)]);

file_put_contents("$root/src/Generated/Operations.php", $operationsFile);
file_put_contents("$root/src/Generated/Types.php", $typesFile);
echo 'Generated ' . count($operations) . ' operations and ' . count($schemas) . " schemas from openapi/openapi.json\n";
